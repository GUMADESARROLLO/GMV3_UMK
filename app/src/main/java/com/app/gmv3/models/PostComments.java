package com.app.gmv3.models;

public class PostComments {
    String id_comments;
    String id_post;
    String comments;
    String created_by;
    String created_at;

    public String getId_comments() {
        return id_comments;
    }

    public String getId_post() {
        return id_post;
    }

    public String getComments() {
        return comments;
    }

    public String getCreated_by() {
        return created_by;
    }

    public String getCreated_at() {
        return created_at;
    }
}
